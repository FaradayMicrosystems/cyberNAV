// Builds simulator/data/network.js (the bundled demo city) from an OSM road extract in GeoJSON.
//
// Source used for the prototype: central Gothenburg, Sweden, as shipped in the
// `large-network.json` test fixture of the npm package `geojson-path-finder`
// (data © OpenStreetMap contributors, ODbL). Usage:
//   npm pack geojson-path-finder && tar xzf geojson-path-finder-*.tgz
//   node simulator/tools/build-data.mjs package/test/large-network.json
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { packRoads } from "../core/pack.js";

const src = process.argv[2];
if (!src) { console.error("usage: build-data.mjs <roads.geojson>"); process.exit(1); }
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../data/network.js");
const gj = JSON.parse(fs.readFileSync(src, "utf8"));
const ways = gj.features.filter(f => f.geometry?.type === "LineString").map(f => ({ coords: f.geometry.coordinates, tags: f.properties || {} }));
const data = packRoads(ways, "Road data © OpenStreetMap contributors (ODbL). Demo extract: central Gothenburg, Sweden.");
fs.writeFileSync(out, "// Generated by tools/build-data.mjs. Do not edit.\nexport default " + JSON.stringify(data) + ";\n");
console.log(`ways ${data.ways.length}, nodes ${data.nodes.length / 2}, names ${data.names.length}, ${(fs.statSync(out).size / 1024).toFixed(0)} KB`);
